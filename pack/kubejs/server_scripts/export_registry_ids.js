// Dev tool: writes every registered item and entity type ID to kubejs/exported/createwars_registry.json
// when the server loads. tools/check_quest_refs.py prefers this file over scanning jars, because jars
// can ship item models/names for things that are never registered (2026-11-21: rha:hatcholive, which
// the game turned into ftbquests:missing_item). Cheap (one pass over the registries) and harmless for
// players. Safe to remove from a release build.
// 2026-11-22: also writes kubejs/exported/createwars_recipes.json (every loaded recipe's outputs and
// inputs, after all KubeJS changes) and the c:hidden_from_recipe_viewers tag, for tools/audit_quests.py.
// Rhino note: no const/let inside nested blocks (try, loop bodies); it reports "redeclaration of var".

function createwarsRegistryIds(access, kind) {
  const out = []
  access.registryOrThrow(kind).keySet().forEach(k => out.push(String(k)))
  out.sort()
  return out
}

function createwarsExportRegistry(server) {
  const regs = Java.loadClass('net.minecraft.core.registries.Registries')
  const access = server.registryAccess()
  JsonIO.write('kubejs/exported/createwars_registry.json', {
    note: 'Generated by export_registry_ids.js on server load. Do not edit.',
    items: createwarsRegistryIds(access, regs.ITEM),
    entities: createwarsRegistryIds(access, regs.ENTITY_TYPE)
  })
}

// Recipe JSON -> {type, out: [ids], in: [ids or #tags]}. Outputs are anything under a result/results/output
// key; inputs are everything else. Encoded from the live recipe objects, so removals/replacements are included.
function createwarsCollectIds(json, isOut, outs, ins) {
  if (json == null) return
  if (json.isJsonArray()) {
    json.getAsJsonArray().forEach(e => createwarsCollectIds(e, isOut, outs, ins))
    return
  }
  if (!json.isJsonObject()) return
  json.getAsJsonObject().entrySet().forEach(en => {
    const k = String(en.getKey())
    const v = en.getValue()
    const out2 = isOut || k == 'result' || k == 'results' || k == 'output' || k == 'outputs'
    if ((k == 'id' || k == 'item' || k == 'fluid' || k == 'tag') && v.isJsonPrimitive()) {
      const s = (k == 'tag' ? '#' : '') + String(v.getAsString())
      if (out2) outs.push(s); else ins.push(s)
    } else {
      createwarsCollectIds(v, out2, outs, ins)
    }
  })
}

function createwarsFailedRecipe(server, holder) {
  const outF = []
  try {
    outF.push(String(holder.value().getResultItem(server.registryAccess()).getItem().builtInRegistryHolder().key().location()))
  } catch (e) {
    // some custom recipes have no single result
  }
  return { id: String(holder.id()), type: String(holder.value().getType()), out: outF, in: [], encode_failed: true }
}

function createwarsExportRecipes(server) {
  const JsonOps = Java.loadClass('com.mojang.serialization.JsonOps')
  const Recipe = Java.loadClass('net.minecraft.world.item.crafting.Recipe')
  const ops = server.registryAccess().createSerializationContext(JsonOps.INSTANCE)
  const recipes = []
  let failed = 0
  server.getRecipeManager().getRecipes().forEach(holder => {
    const res = Recipe.CODEC.encodeStart(ops, holder.value()).result()
    if (!res.isPresent()) {
      // Codec failed (custom recipe class): still record its type and the result the game reports.
      failed++
      recipes.push(createwarsFailedRecipe(server, holder))
      return
    }
    const outs = [], ins = []
    const json = res.get()
    createwarsCollectIds(json, false, outs, ins)
    recipes.push({ id: String(holder.id()), type: String(json.getAsJsonObject().get('type').getAsString()), out: outs, in: ins })
  })
  const BuiltIn = Java.loadClass('net.minecraft.core.registries.BuiltInRegistries')
  const TagKey = Java.loadClass('net.minecraft.tags.TagKey')
  const RL = Java.loadClass('net.minecraft.resources.ResourceLocation')
  const regs = Java.loadClass('net.minecraft.core.registries.Registries')
  const hidden = []
  const tag = BuiltIn.ITEM.getTag(TagKey.create(regs.ITEM, RL.parse('c:hidden_from_recipe_viewers')))
  if (tag.isPresent()) tag.get().forEach(h => hidden.push(String(h.unwrapKey().get().location())))
  JsonIO.write('kubejs/exported/createwars_recipes.json', {
    note: 'Generated by export_registry_ids.js on server load. Do not edit.',
    encode_failed: failed,
    hidden: hidden,
    recipes: recipes
  })
}

ServerEvents.loaded(event => {
  try {
    createwarsExportRegistry(event.server)
  } catch (e) {
    console.warn('[createwars] export_registry_ids.js failed: ' + e)
  }
  try {
    createwarsExportRecipes(event.server)
  } catch (e) {
    console.warn('[createwars] recipe export failed: ' + e)
  }
})
