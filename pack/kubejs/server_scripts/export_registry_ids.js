// Dev tool: writes every registered item and entity type ID to kubejs/exported/createwars_registry.json
// when the server loads. tools/check_quest_refs.py prefers this file over scanning jars, because jars
// can ship item models/names for things that are never registered (2026-11-21: rha:hatcholive, which
// the game turned into ftbquests:missing_item). Cheap (one pass over the registries) and harmless for
// players. Safe to remove from a release build.
// Rhino note: no const/let inside nested blocks (try, loop bodies); it reports "redeclaration of var".

function createwarsRegistryIds(access, kind) {
  const out = []
  access.registryOrThrow(kind).keySet().forEach(k => out.push(String(k)))
  out.sort()
  return out
}

function createwarsExportRegistry(server) {
  const regs = Java.loadClass('net.minecraft.core.registries.Registries')
  const access = server.registryAccess()
  JsonIO.write('kubejs/exported/createwars_registry.json', {
    note: 'Generated by export_registry_ids.js on server load. Do not edit.',
    items: createwarsRegistryIds(access, regs.ITEM),
    entities: createwarsRegistryIds(access, regs.ENTITY_TYPE)
  })
}

ServerEvents.loaded(event => {
  try {
    createwarsExportRegistry(event.server)
  } catch (e) {
    console.warn('[createwars] export_registry_ids.js failed: ' + e)
  }
})
